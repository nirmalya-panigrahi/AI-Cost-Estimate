function buildDefaultUsages(config: PricingConfig, overrides: Record<string, number> = {}): Record<string, number> {
  const usages: Record<string, number> = {};
  for (const c of config.components) {
    usages[c.id] = overrides[c.id] ?? c.defaultUsageUnits;
  }
  return usages;
}

function buildToggleStates(
  config: PricingConfig,
  overrides: Record<string, { enabled: boolean; reusePercentage?: number }> = {}
) {
  const result: ScenarioConfig['legacyToggles'] = {};
  for (const t of config.legacyToggles) {
    const ov = overrides[t.id];
    result[t.id] = {
      enabled: ov?.enabled ?? false,
      reusePercentage: ov?.reusePercentage ?? t.defaultReusePercentage,
      efficiencyFactor: t.defaultEfficiencyFactor,
    };
  }
  return result;
}

